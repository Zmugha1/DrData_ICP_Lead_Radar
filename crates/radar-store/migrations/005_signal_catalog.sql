-- Signal catalogue. Availability is not a column. A command joins
-- source_id to the loaded config registry so status updates when a
-- source is built. A stored availability value would go stale the
-- day the work is done.

CREATE TABLE vertical_catalog (
    vertical_key TEXT PRIMARY KEY,
    label TEXT NOT NULL,
    tier TEXT NOT NULL
);

CREATE TABLE signal_catalog (
    signal_key TEXT PRIMARY KEY,
    label TEXT NOT NULL,
    description TEXT NOT NULL,
    source_id TEXT NOT NULL,
    detection_method TEXT NOT NULL
        CHECK (detection_method IN (
            'run comparison',
            'nightly diff',
            'external file',
            'manual upload',
            'not yet determined'
        ))
);

CREATE TABLE signal_direction (
    signal_key TEXT NOT NULL REFERENCES signal_catalog (signal_key),
    vertical_key TEXT NOT NULL REFERENCES vertical_catalog (vertical_key),
    direction TEXT NOT NULL CHECK (direction IN ('favourable', 'unfavourable', 'ask')),
    rationale TEXT NOT NULL,
    PRIMARY KEY (signal_key, vertical_key)
);

